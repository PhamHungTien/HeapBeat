import type { Song } from "../lib/heapbeat";

const PIANO_NOTICE_URL = "./licenses/HEAPBEAT-PIANO-NOTICE.txt";

type PianoTrack = {
  slug: string;
  title: string;
  performer: string;
  originalArtist: string;
  genre: string;
  durationSec: number;
  color: string;
  coverTone: Song["coverTone"];
  mood: string;
};

function pianoSong(track: PianoTrack): Song {
  return {
    id: `song-${track.slug}`,
    canonicalKey: `local:${track.slug}`,
    title: track.title,
    artist: track.performer,
    album: "Piano Cover",
    genre: track.genre,
    durationSec: track.durationSec,
    color: track.color,
    coverTone: track.coverTone,
    mood: track.mood,
    sourceProvider: "internal",
    sourceUrl: `/music/${track.slug}.mp3`,
    licenseType: "USER_PROVIDED",
    licenseUrl: PIANO_NOTICE_URL,
    attributionText: `${track.performer}; tác phẩm gốc: ${track.originalArtist}. Tệp do chủ dự án cung cấp cho bản demo nội bộ.`,
    publicPlaybackAllowed: true,
    approvalStatus: "approved",
    coverUrl: "",
  };
}

